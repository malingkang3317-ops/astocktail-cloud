#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""AStockTail A/B/C historical minute-shape comparison, CACHE ONLY.

Inputs (generated by astocktail_backtest_5days_v3.py):
 replay_reports/five_days_v3/five_day_report.json
 replay_reports/five_days/cache/minutes/{full_code}.json
 replay_reports/five_days/cache/indices/{index_code}.json

No AKShare, eltdx requests, GitHub pushes, or ServerChan notifications.
Retains the V3 historical PROXY basic-candidate sample (not point-in-time
verified circulating shares, not complete universe). No lookahead in signals:
minutes strictly <= 14:49. Outcome uses next trading day's closing price
from prior V3 report and is for evaluation only, not for the selection signal.
"""
import argparse
import csv
import json
import math
import statistics
from collections import Counter
from datetime import datetime
from pathlib import Path
from zoneinfo import ZoneInfo

TZ = ZoneInfo('Asia/Shanghai')
DAYS = ['2026-10-28','2026-10-29','2026-10-30','2026-11-02','2026-11-03']
LABELS = {
    'volume_tail_above_prior_baseline':'尾段成交量高于第3、4段中位数均值',
    'stronger_than_index':'分时强于对应指数',
    'vwap_above_70pct':'至少70%分钟收盘价位于VWAP上方',
}
SHAPES = {
    'A':'14:40–14:49突破13:01以来此前最高价，再回踩≥0.05%且守住VWAP',
    'B':'14:40–14:49突破14:00以来此前最高价，再回踩≥0.05%且守住VWAP',
    'C':'14:40–14:49触及13:01以来此前最高价0.5%以内，再回踩≥0.05%且守住VWAP',
}


def index_for(code):
    if code.startswith('sz30'): return 'sz399006'
    if code.startswith('sh68'): return 'sh000688'
    return 'sh000001' if code.startswith('sh') else 'sz399001'


def minute_points(raw, day):
    points=[]
    for b in raw:
        try:
            ts=datetime.fromisoformat(str(b['time'])).astimezone(TZ)
        except (TypeError, ValueError, KeyError) as exc:
            raise ValueError('缓存时间戳非法') from exc
        tm=ts.strftime('%H:%M')
        if ts.date().isoformat()!=day or tm>'14:49': continue
        if not ('09:31'<=tm<='11:30' or '13:01'<=tm<='14:49'): continue
        p={k:float(b.get(k) or 0) for k in ('close','high','low','amount','volume_lots')}
        if not all(math.isfinite(x) for x in p.values()): raise ValueError('分钟值含NaN/inf')
        if p['close']<=0 or p['high']<p['low'] or p['low']<=0 or p['amount']<0 or p['volume_lots']<0:
            raise ValueError(f'{tm}分钟价格或成交量异常')
        points.append({'time':tm,'price':p['close'],'high':p['high'],'low':p['low'],
                       'amount':p['amount'],'volume':p['volume_lots']})
    points.sort(key=lambda p:p['time'])
    expected=[]
    for h,a,z in ((9,31,59),(10,0,59),(11,0,30),(13,1,59),(14,0,49)):
        expected.extend(f'{h:02d}:{m:02d}' for m in range(a,z+1))
    if [p['time'] for p in points]!=expected:
        raise ValueError(f'{day}分钟数据不完整或重复: 得到{len(points)}/{len(expected)}')
    total_amount=total_shares=0.0
    for p in points:
        total_amount+=p['amount'];total_shares+=p['volume']*100
        if total_shares<=0: raise ValueError('累计成交量为0，无法生成VWAP')
        p['vwap']=total_amount/total_shares
    return points


def index_series(raw,day):
    idx={}
    for b in raw:
        ts=datetime.fromisoformat(str(b['time'])).astimezone(TZ)
        tm=ts.strftime('%H:%M')
        if ts.date().isoformat()==day and tm<='14:49':
            price=float(b.get('close') or 0)
            if not math.isfinite(price) or price<=0:raise ValueError('指数价格不合法')
            if tm in idx:raise ValueError('指数分钟时间重复')
            idx[tm]=price
    return idx


def condition_flags(points,indices):
    matched=[(p,indices[p['time']]) for p in points if p['time'] in indices]
    if len(matched)<220: raise ValueError(f'指数有效分钟对齐不足:{len(matched)}')
    rel=100*((matched[-1][0]['price']/matched[0][0]['price']-1)-
              (matched[-1][1]/matched[0][1]-1))
    above=sum(p['price']>=p['vwap'] for p in points)/len(points)
    seq=[p for p in points if p['time']>='10:00']
    if len(seq)!=200: raise ValueError(f'10:00后有效分钟数错误:{len(seq)}')
    medians=[statistics.median(p['volume'] for p in seq[i:i+40]) for i in range(0,200,40)]
    baseline=(medians[2]+medians[3])/2
    if baseline<=0: raise ValueError('第3、4段成交量中位数基准为0')
    return ({'volume_tail_above_prior_baseline':medians[4]>baseline,
             'stronger_than_index':rel>0,
             'vwap_above_70pct':above>=0.70},
            {'volume_medians':medians,'tail_over_baseline':round(medians[4]/baseline,5),
             'outperformance_pct_points':round(rel,5),'above_vwap_fraction':round(above,5)})


def shape_events(points,variant):
    """Only historical highs known BEFORE a given 1-minute bar may be used.
    Breakout/near-high is observed using that completed bar high. The pullback
    must occur in a strictly later completed minute and stay above its VWAP;
    every intervening minute's low through the pullback must respect VWAP.
    A/B: true high breakout; C: >=99.5% of prior afternoon high (includes breakouts).
    All variants use >=0.05% pullback on a later bar for comparability.
    """
    if variant not in SHAPES:raise ValueError(variant)
    base_start='14:00' if variant=='B' else '13:01'
    running=-float('inf')
    candidates=[]
    for i,p in enumerate(points):
        tm=p['time']
        if tm < base_start:continue
        # Compare against earlier bars only, never include the current high in baseline.
        if '14:40'<=tm<='14:49' and running>0:
            if variant=='C': qualify=p['high']>=running*0.995
            else: qualify=p['high']>running
            if qualify:candidates.append((i,running))
        running=max(running,p['high'])
    event=None
    for i,prior_high in candidates:
        peak=points[i]['high']
        for j in range(i+1,len(points)):
            low=points[j]['low']
            drop=(peak-low)/peak
            if drop>=0.0005 and all(p['low']>=p['vwap'] for p in points[i+1:j+1]):
                event={'setup_minute':points[i]['time'],'pullback_minute':points[j]['time'],
                       'setup_high':peak,'prior_high':prior_high,'drop_pct':round(drop*100,5),
                       'pullback_low':low,'pullback_vwap':round(points[j]['vwap'],5)}
                break
        if event is not None:break
    return {'setup':bool(candidates),'pullback':event is not None,'event':event,
            'setup_minutes':[points[i]['time'] for i,_ in candidates]}


def summary(values):
    good=[float(x) for x in values if x is not None and math.isfinite(float(x))]
    return {'n':len(good),'mean_pct':round(statistics.mean(good),4) if good else None,
            'median_pct':round(statistics.median(good),4) if good else None,
            'win_rate_pct':round(100*sum(x>0 for x in good)/len(good),2) if good else None,
            'worst_pct':round(min(good),4) if good else None,
            'best_pct':round(max(good),4) if good else None}


def run(root,output,require_all=False):
    source=root/'replay_reports'/'five_days_v3'/'five_day_report.json'
    cache=root/'replay_reports'/'five_days'/'cache'
    if not source.is_file():raise FileNotFoundError(f'找不到V3报告: {source}')
    data=json.loads(source.read_text(encoding='utf-8'))
    output.mkdir(parents=True,exist_ok=True)
    rows=[]; errors=[]
    cache_stats=Counter()
    for day in DAYS:
        item=data.get('per_day',{}).get(day)
        if not isinstance(item,dict):
            errors.append({'date':day,'error':'源V3报告缺少此交易日'});continue
        original=item.get('top_candidates',[])
        print(f'{day}: 读取{len(original)}条V3基础候选记录',flush=True)
        for rec in original:
            code=rec.get('code','')
            try:
                if not rec.get('basic') or not rec.get('technical'):
                    raise ValueError('缺少V3已通过的基础代理条件或技术明细')
                # V3 top_candidates only records basic_price_volume AND profile_proxy passes.
                minute_file=cache/'minutes'/f'{code}.json'
                idx_code=index_for(code)
                index_file=cache/'indices'/f'{idx_code}.json'
                for file in (minute_file,index_file):
                    if not file.is_file():raise FileNotFoundError(f'缺少行情缓存:{file}')
                points=minute_points(json.loads(minute_file.read_text(encoding='utf-8')),day)
                index=index_series(json.loads(index_file.read_text(encoding='utf-8')),day)
                flags,metrics=condition_flags(points,index)
                shape={v:shape_events(points,v) for v in SHAPES}
                common=all(flags.values())
                outcome=rec.get('next_trading_day_close_return_pct_vs_1449')
                row={'date':day,'code':code,'name':rec.get('name'),
                     'basic':rec['basic'],'common_flags':flags,'common_metrics':metrics,
                     'variants':{v:{**shape[v],'all_technical_pass':common and shape[v]['pullback']}
                                 for v in SHAPES},
                     'next_day_close_return_pct_vs_1449':outcome,
                     'historical_shares_verified':rec.get('historical_shares_verified',False)}
                # Even though technically 'ready', this is a backtest proxy.
                rows.append(row);cache_stats['validated']+=1
            except Exception as exc:
                cache_stats['failed']+=1
                errors.append({'date':day,'code':code,'error':f'{type(exc).__name__}: {exc}'})
    per_day={}
    for day in DAYS:
        source_day=data.get('per_day',{}).get(day,{})
        subset=[r for r in rows if r['date']==day]
        incomplete=(source_day.get('profile_proxy_pass',0)!=len(subset))
        st={'source_basic_proxy_candidates':source_day.get('profile_proxy_pass',0),
            'evaluated':len(subset),'incomplete':incomplete,
            'missing_daily_symbols':source_day.get('daily_missing'),
            'source_complete':source_day.get('complete'),
            'common_pass_rates':{},'variants':{}}
        for flag,label in LABELS.items():
            n=sum(r['common_flags'][flag] for r in subset)
            st['common_pass_rates'][flag]={'passed':n,'total':len(subset),
                                          'rate_pct':round(n/len(subset)*100,2) if subset else None}
        for v in SHAPES:
            setups=[r for r in subset if r['variants'][v]['setup']]
            pullbacks=[r for r in subset if r['variants'][v]['pullback']]
            passed=[r for r in subset if r['variants'][v]['all_technical_pass']]
            st['variants'][v]={'setups':len(setups),'valid_pullbacks':len(pullbacks),
                'all_technical_pass':len(passed),
                'setup_pass_rate_pct':round(100*len(setups)/len(subset),2) if subset else None,
                'pullback_pass_rate_pct':round(100*len(pullbacks)/len(subset),2) if subset else None,
                'all_pass_rate_pct':round(100*len(passed)/len(subset),2) if subset else None,
                'next_day_close_vs_1449':summary(r['next_day_close_return_pct_vs_1449'] for r in passed),
                'passing_stocks':[{'code':r['code'],'name':r['name'],'return_pct':r['next_day_close_return_pct_vs_1449']}
                                  for r in passed]}
        per_day[day]=st
    totals={}
    for v in SHAPES:
        selected=[r for r in rows if r['variants'][v]['all_technical_pass']]
        totals[v]={'all_technical_pass':len(selected),
                   'unique_stocks':len({r['code'] for r in selected}),
                   'next_day_close_vs_1449':summary(r['next_day_close_return_pct_vs_1449'] for r in selected)}
    total_basic=sum(item.get('profile_proxy_pass',0) for item in data['per_day'].values())
    result={'metadata':{'mode':'A/B/C historical PROXY comparison, NOT validated live recommendations',
       'days':DAYS,'cutoff':'14:49 completed 1m bars','sample':'V3 basic proxy candidates only',
       'shape_definitions':SHAPES,'common_conditions':LABELS,
       'return_definition':'next trading day unadjusted CLOSE / signal day 14:49 price - 1 (from V3 report)',
       'limitations':['V3 source historical free-float shares not as-of independently validated',
          'V3 universe has missing symbols and excludes historical delisted stocks; survivor bias',
          'V3 historical daily OHLC necessary-candidate filter, not actual 14:30 candidate pool',
          'OHLC minute bars cannot determine within-minute price-event order',
          '14:50 forming 1m bar excluded; only completed bars through 14:49',
          'Next-day close/14:49 price is NOT an executable strategy return (no trading costs)',
          'A/B/C variations are hypotheses; small 5-day sample may overfit',
          'Current minutely sources may be restated and historical shares unverified'],
       'source':str(source),'cached_only':True,'source_basic_proxy_candidates':total_basic,
       'successfully_evaluated':len(rows),'errors':len(errors),'complete':all(not d['incomplete'] and d['source_complete'] is True for d in per_day.values())},
       'per_day':per_day,'overall':totals,'candidate_details':rows,'errors':errors}
    p=output/'abc_report.json'
    p.write_text(json.dumps(result,ensure_ascii=False,indent=2),encoding='utf-8')
    with (output/'abc_daily_summary.csv').open('w',newline='',encoding='utf-8-sig') as f:
        w=csv.writer(f)
        w.writerow(['date','variant','basic_proxy_candidates','evaluated','common_volume_pass','common_index_pass','common_vwap_pass',
                    'shape_setup_pass','shape_pullback_pass','all_technical_pass','next_day_return_n','next_day_mean_pct',
                    'next_day_win_rate_pct','next_day_worst_pct','incomplete'])
        for day,s in per_day.items():
            for v,a in s['variants'].items():
                perf=a['next_day_close_vs_1449']
                w.writerow([day,v,s['source_basic_proxy_candidates'],s['evaluated'],
                     s['common_pass_rates']['volume_tail_above_prior_baseline']['passed'],
                     s['common_pass_rates']['stronger_than_index']['passed'],
                     s['common_pass_rates']['vwap_above_70pct']['passed'],
                     a['setups'],a['valid_pullbacks'],a['all_technical_pass'],
                     perf['n'],perf['mean_pct'],perf['win_rate_pct'],perf['worst_pct'],s['incomplete']])
    with (output/'abc_candidates.csv').open('w',newline='',encoding='utf-8-sig') as f:
        w=csv.writer(f)
        w.writerow(['date','code','name','volume','index','vwap','A_setup','A_pullback','A_all',
                    'B_setup','B_pullback','B_all','C_setup','C_pullback','C_all','next_day_close_return_pct_vs_1449'])
        for r in rows:
            w.writerow([r['date'],r['code'],r['name'],
              *[r['common_flags'][k] for k in LABELS],
              *[r['variants'][v][k] for v in SHAPES for k in ('setup','pullback','all_technical_pass')],
              r['next_day_close_return_pct_vs_1449']])
    print('\n=== A/B/C五日回放对照（仅历史代理） ===')
    for day,s in per_day.items():
        print(day,'基础候选',s['source_basic_proxy_candidates'],'完成重算',s['evaluated'])
        for v,x in s['variants'].items():
            print(' ',v,'形态触发',x['setups'],'有效回踩',x['valid_pullbacks'],
                  '完整技术通过',x['all_technical_pass'],
                  '次日收益统计',x['next_day_close_vs_1449'])
    print('总样本',len(rows),'错误',len(errors),'严格完整覆盖',result['metadata']['complete'])
    print('报告:',p)
    if require_all and errors:raise SystemExit(2)
    return result


def main():
    parser=argparse.ArgumentParser(description='AStockTail V3 A/B/C cached-only five-day shape comparison')
    parser.add_argument('--root',type=Path,default=Path(__file__).resolve().parent,
                        help='AStockTail repository root containing replay_reports/')
    parser.add_argument('--out',type=Path,default=None)
    parser.add_argument('--require-all',action='store_true',help='return nonzero exit code if any candidate lacks cached data')
    args=parser.parse_args()
    root=args.root.resolve();out=(args.out or (root/'replay_reports'/'five_days_abc')).resolve()
    run(root,out,args.require_all)

if __name__=='__main__': main()
